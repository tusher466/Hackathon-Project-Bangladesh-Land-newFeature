// Anchor coordinate references for synthetic mouzas
const MOUZA_COORDS = {
  BADDA: { lat: 23.7820, lng: 90.4260 },
  TEJGAON: { lat: 23.7590, lng: 90.3920 },
  SAVAR: { lat: 23.8480, lng: 90.2600 },
};

function createRecord(data: {
  id: string;
  surveyType: 'CS' | 'SA' | 'RS' | 'BS';
  surveyYear: number;
  dagNo: string;
  khatianNo: string;
  mouzaId: string;
  mouzaNameEn: string;
  mouzaNameBn: string;
  jlNo: string;
  sheetNo: string;
  division: string;
  district: string;
  upazila: string;
  recordedArea: number;
  recordedUnit: 'decimal' | 'acre' | 'bigha' | 'katha' | 'sqft' | 'sqm';
  sourceReference: string;
  khatianOwnerNames: string[];
  remarks: string;
  crossReferences: string[];
  hasGeometry: boolean;
  geoOffset?: { latOff: number; lngOff: number; width: number; height: number };
  flags?: string[];
}): ParcelRecord {
  const normArea = convertToStandardDecimal(data.recordedArea, data.recordedUnit);
  const sqm = decimalToSqm(normArea);

  let geometry = null;
  if (data.hasGeometry && data.geoOffset) {
    const base = data.mouzaId.includes('tejgaon')
      ? MOUZA_COORDS.TEJGAON
      : data.mouzaId.includes('savar')
      ? MOUZA_COORDS.SAVAR
      : MOUZA_COORDS.BADDA;

    geometry = generateSyntheticParcelPolygon(
      base.lat + data.geoOffset.latOff,
      base.lng + data.geoOffset.lngOff,
      data.geoOffset.width,
      data.geoOffset.height,
      parseInt(data.dagNo.replace(/\D/g, '') || '1', 10)
    );
  }

  const flags = data.flags || [];
  if (!data.hasGeometry) flags.push('MISSING_CADASTRAL_GEOMETRY');
  if (data.crossReferences.length === 0) flags.push('NO_ARCHIVAL_CROSS_REFERENCE');

  return {
    id: data.id,
    surveyType: data.surveyType,
    surveyYear: data.surveyYear,
    dagNo: data.dagNo,
    dagNoBn: toBengaliDigits(data.dagNo),
    khatianNo: data.khatianNo,
    khatianNoBn: toBengaliDigits(data.khatianNo),
    mouzaId: data.mouzaId,
    mouzaNameEn: data.mouzaNameEn,
    mouzaNameBn: data.mouzaNameBn,
    jlNo: data.jlNo,
    jlNoBn: toBengaliDigits(data.jlNo),
    sheetNo: data.sheetNo,
    division: data.division,
    district: data.district,
    upazila: data.upazila,
    recordedArea: data.recordedArea,
    recordedAreaBn: toBengaliDigits(data.recordedArea),
    recordedUnit: data.recordedUnit,
    normalizedAreaDecimal: normArea,
    normalizedAreaSqm: sqm,
    sourceReference: data.sourceReference,
    khatianOwnerNames: data.khatianOwnerNames,
    remarks: data.remarks,
    crossReferences: data.crossReferences,
    geometry,
    dataQuality: {
      isGeometryAvailable: data.hasGeometry,
      isCrossReferencePresent: data.crossReferences.length > 0,
      isAreaVerified: true,
      hasMissingAttributes: !data.hasGeometry || data.crossReferences.length === 0,
      qualityScore: data.hasGeometry && data.crossReferences.length > 0 ? 95 : 68,
      flags,
    },
    createdAt: new Date().toISOString(),
  };
}

